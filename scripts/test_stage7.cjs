const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const learning=require('../learning.js');
const article={id:'k',kind:'knowledge',title:'示例',category:'邏輯學',url:'https://example.org/k',source:'示例來源',verification:'publisher_domain_checked',reuse_license:'approved',content_complete:true,translation_status:'original_zh_hant',evidence_original:['前提是指在論證中用來支持結論的陳述。這是一個用來檢查閱讀節錄是否能回到原文的示例段落，段落足夠長，而且來源文字必須以原本順序完整保留。'],quiz:[{question:'支持結論的陳述稱作什麼？',options:['前提','廣告'],answer:0,explanation:'前提用來支持結論。',paragraph:1}]};
const now=new Date('2026-11-20T01:00:00Z');
const news={...article,id:'n',url:'https://example.org/n',kind:'news',published_at:'2026-11-19T00:00:00Z'};
const data=[article,news,{...news,url:'https://example.org/headline',content_complete:false,content_scope:'media_headline'}, {...news,url:'https://example.org/future',published_at:'2026-11-21T00:00:00Z'}];
const digest=learning.digest(data,now);
assert.equal(digest.entries.length,2);
assert.equal(digest.newsCount,1);
assert.equal(digest.date,'2026-11-20');
for(const row of digest.entries) assert.ok(row.article.evidence_original[row.paragraph-1].includes(row.text));
assert.deepEqual(digest,learning.digest(data,now));
assert.equal(learning.digest([{...article,reuse_license:'unknown'}],now).entries.length,0);
assert.equal(learning.digest([{...article,translation_status:'translation_pending'}],now).entries.length,0);
assert.equal(learning.digest([{...news,published_at:'2026-01-01'}],now).newsCount,0);
const results={k:{total:1,score:0,answers:[1]},legacy:{total:1,score:0}};
const untouched=JSON.stringify(results);
const review=learning.reviews([article],results,a=>a.quiz);
assert.equal(review.items.length,1);
assert.equal(review.unavailable.length,1);
assert.equal(review.items[0].paragraph,1);
assert.equal(JSON.stringify(results),untouched);
assert.equal(learning.reviews([article],{k:{total:1,score:1,answers:[0]}},a=>a.quiz).items.length,0);
assert.equal(learning.reviews([{...article,quiz:[{...article.quiz[0],paragraph:999}]}],results,a=>a.quiz).items[0].paragraph,null);
const unsafe={...article,title:'<img src=x onerror=alert(1)>',url:'javascript:alert(1)'};
assert.ok(!learning.digestHtml([unsafe],now).includes('onerror='));
assert.ok(learning.importanceHtml({primary_topic:'politics_policy',articles:[{...news,published_at:'invalid'}]}).includes('日期不明'));
const html=fs.readFileSync('preview/stage7-acceptance.html','utf8');
for(const script of [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)]) new vm.Script(script[1]);
const css=html.match(/<style>([\s\S]*?)<\/style>/)[1];
assert.ok(css.startsWith(':root{'), 'offline CSS starts at the root selector after the complete font import');
assert.ok(!css.includes('display=swap'), 'font URL fragments cannot remain in inline CSS');
assert.ok(css.includes('.mast{padding:35px 0 25px;display:flex;'));
assert.ok(!html.includes('<script src='));
assert.ok(!html.includes('localStorage'));
assert.ok(!html.includes("navigator.serviceWorker.register"));
assert.ok(html.includes("currentTab = 'learning'"));
console.log('Passed: deterministic sourced digest, dates, licensing, Chinese eligibility, wrong-answer review, legacy results, escaping and isolated preview.');
